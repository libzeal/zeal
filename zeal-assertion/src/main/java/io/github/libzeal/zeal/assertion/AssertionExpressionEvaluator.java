package io.github.libzeal.zeal.assertion;

import io.github.libzeal.zeal.logic.Expression;
import io.github.libzeal.zeal.logic.evaluation.Evaluation;
import io.github.libzeal.zeal.logic.format.EvaluationFormatter;
import io.github.libzeal.zeal.logic.unary.UnaryExpression;
import org.jspecify.annotations.Nullable;

import static java.util.Objects.requireNonNull;

/**
 * An evaluator responsible for handling the core logic of asserting an
 * expression, such as when to throw an exception and how to handle error
 * cases.
 *
 * @param <N>
 *         The type of exception thrown when an evaluation fails and the subject
 *         of the evaluated {@link UnaryExpression} is {@code null}.
 * @param <F>
 *         The type of exception thrown when any other evaluation fails.
 *
 * @author Justin Albano
 */
final class AssertionExpressionEvaluator<N extends Throwable, F extends Throwable> {

    @SuppressWarnings("java:S1214")
    interface Messages {
        String NULL_EXPRESSION = "Cannot evaluate null expression";
        String NULL_EVALUATION = "Cannot process null evaluation";
    }

    private final EvaluationFormatter formatter;
    private final ExceptionSupplier<N> onNullExceptionFunc;
    private final ExceptionSupplier<F> onFailExceptionFunc;

    /**
     * Creates a new evaluator.
     *
     * @param formatter
     *         The formatter to use when creating exception messages.
     * @param onNullExceptionFunc
     *         A function that consumes a message and returns the appropriate
     *         exception to throw when an evaluation fails and the subject of
     *         the evaluated {@link UnaryExpression} is {@code null}. If the
     *         expression is not a {@link UnaryExpression}, this exception is
     *         unused.
     * @param onFailExceptionFunc
     *         A function that consumes a message and returns the appropriate
     *         exception to throw when an evaluation fails and the expression is
     *         either:
     *         <ol>
     *             <li>Not a {@link UnaryExpression}</li>
     *             <li>A {@link UnaryExpression} with a subject that is not
     *             {@code null}</li>
     *         </ol>
     *
     * @throws NullPointerException
     *         Any of the supplied arguments are {@code null}.
     */
    AssertionExpressionEvaluator(
            final EvaluationFormatter formatter, final ExceptionSupplier<N> onNullExceptionFunc,
            final ExceptionSupplier<F> onFailExceptionFunc
    ) {
        this.formatter = requireNonNull(formatter);
        this.onNullExceptionFunc = requireNonNull(onNullExceptionFunc);
        this.onFailExceptionFunc = requireNonNull(onFailExceptionFunc);
    }

    /**
     * Evaluates the supplied expression and throws the configured exceptions if
     * the evaluation fails.
     *
     * @param expression
     *         The expression to evaluate.
     * @param message
     *         The message to use for the exceptions thrown if the evaluation
     *         fails. This message is prepended to the message generated by the
     *         configured formatter. If a {@code null} message is supplied, an
     *         empty message is prepended to the formatted message.
     * @param <T>
     *         The type of the subject.
     *
     * @return The subject of the expression if the evaluation succeeds.
     *
     * @throws N
     *         The evaluation fails and the subject of the evaluated
     *         {@link UnaryExpression} is {@code null}.
     * @throws F
     *         The evaluation fails and the expression has a subject that is not
     *         {@code null}.
     * @throws NullPointerException
     *         The supplied expression is {@code null} or the evaluation from
     *         the supplied expression (when calling
     *         {@link UnaryExpression#evaluate()}) is {@code null}.
     */
    public <T> T evaluate(final UnaryExpression<T> expression, final @Nullable String message) throws N, F {

        if (expression == null) {
            throw new NullPointerException(Messages.NULL_EXPRESSION);
        }

        final Evaluation evaluation = expression.evaluate();

        if (evaluation == null) {
            throw new NullPointerException(Messages.NULL_EVALUATION);
        }

        final T subject = expression.subject();

        if (evaluation.isFalse()) {

            final String formattedMessage = formatMessage(formatter, message, evaluation);

            if (subject == null) {
                throw onNullExceptionFunc.create(formattedMessage);
            }
            else {
                throw onFailExceptionFunc.create(formattedMessage);
            }
        }
        else {
            return passedSubject(subject);
        }
    }

    @SuppressWarnings("NullAway")
    private static <T> T passedSubject(final @Nullable T subject) {
        // A passing evaluation only has a null subject when every condition
        // accepts null (such as isNull), in which case the null subject is
        // returned
        return subject;
    }

    static String formatMessage(
            final EvaluationFormatter formatter, final @Nullable String message,
            final Evaluation evaluation
    ) {

        final String formattedSuppliedMessage = message == null ? "" : message;

        return formattedSuppliedMessage + "\n\n" + formatter.format(evaluation) + "\n\nStack trace:";
    }

    /**
     * Evaluates the supplied expression and throws the configured exceptions if
     * the evaluation fails. If the supplied expression is a
     * {@link UnaryExpression}, it is evaluated according to
     * {@link #evaluate(UnaryExpression, String)}.
     *
     * @param expression
     *         The expression to evaluate.
     * @param message
     *         The message to use for the exceptions thrown if the evaluation
     *         fails. This message is prepended to the message generated by the
     *         configured formatter. If a {@code null} message is supplied, an
     *         empty message is prepended to the formatted message.
     *
     * @throws N
     *         The evaluation fails and the subject of the evaluated
     *         {@link UnaryExpression} is {@code null}.
     * @throws F
     *         The evaluation fails and the expression is either not a
     *         {@link UnaryExpression} or has a subject that is not
     *         {@code null}.
     * @throws NullPointerException
     *         The supplied expression is {@code null} or the evaluation from
     *         the supplied expression (when calling
     *         {@link Expression#evaluate()}) is {@code null}.
     */
    public void evaluate(
            final Expression expression,
            final @Nullable String message
    ) throws N, F {

        if (expression instanceof final UnaryExpression<?> unaryExpression) {
            evaluate(unaryExpression, message);
            return;
        }

        if (expression == null) {
            throw new NullPointerException(Messages.NULL_EXPRESSION);
        }

        final Evaluation evaluation = expression.evaluate();

        if (evaluation == null) {
            throw new NullPointerException(Messages.NULL_EVALUATION);
        }

        if (evaluation.isFalse()) {

            final String formattedMessage = formatMessage(formatter, message, evaluation);

            throw onFailExceptionFunc.create(formattedMessage);
        }
    }

    /**
     * A function that consumes a message and creates a {@link Throwable}.
     *
     * @param <T>
     *         The type of the exception.
     *
     * @author Justin Albano
     * @since 0.2.0
     */
    @FunctionalInterface
    public interface ExceptionSupplier<T extends Throwable> {

        /**
         * Creates a new {@link Throwable} from the supplied message.
         *
         * @param message
         *         The message to use for the exception.
         *
         * @return The created exception.
         */
        T create(String message);
    }
}
